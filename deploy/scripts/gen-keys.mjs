// Generates deploy/compose/.env with fresh dev secrets. Run: node deploy/scripts/gen-keys.mjs [--force]
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const target = join(dirname(fileURLToPath(import.meta.url)), "..", "compose", ".env");
if (existsSync(target) && !process.argv.includes("--force")) {
  console.log(`${target} already exists. Use --force to overwrite.`);
  process.exit(0);
}

const { publicKey, privateKey } = generateKeyPairSync("rsa", {
  modulusLength: 2048,
  publicKeyEncoding: { type: "spki", format: "pem" },
  privateKeyEncoding: { type: "pkcs8", format: "pem" },
});
const oneLine = (pem) => `"${pem.trim().replace(/\r?\n/g, "\\n")}"`;
const secret = (bytes = 32) => randomBytes(bytes).toString("base64");
const token = () => randomBytes(24).toString("hex");

const lines = [
  "# Generated by deploy/scripts/gen-keys.mjs - local development only, never commit.",
  `JWT_PRIVATE_KEY_PEM=${oneLine(privateKey)}`,
  `JWT_PUBLIC_KEY_PEM=${oneLine(publicKey)}`,
  `PII_ENC_KEY=${secret()}`,
  `PII_HMAC_KEY=${secret()}`,
  `IDENTITY_FEED_KEY=${token()}`,
  `CATALOG_FEED_KEY=${token()}`,
  `ORDER_FEED_KEY=${token()}`,
  `PAYMENT_FEED_KEY=${token()}`,
  `FLEET_FEED_KEY=${token()}`,
  `DB_PASSWORD=${token()}`,
  "GATEWAY=fake",
  "RAZORPAY_KEY_ID=",
  "RAZORPAY_KEY_SECRET=",
  "RAZORPAY_WEBHOOK_SECRET=",
  "",
];
writeFileSync(target, lines.join("\n"), { encoding: "utf8" });
console.log(`Wrote ${target}`);
