// Writes deploy/local/cloud-app.env: fresh secrets and settings for the Google Cloud sandbox VM (git-ignored).
//   node deploy/scripts/gen-cloud-env.mjs --host 34-47-166-37.sslip.io --admin you@example.com [--smoke]
// The database passwords come from deploy/local/gcp.env (created with the Cloud SQL instance). The file is
// a bash script of `export KEY='value'` lines: single quotes keep the PEM "\n" escapes literal.
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const opt = (name) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const host = opt("host");
const admin = opt("admin");
if (!host || !admin) {
  console.error("usage: node gen-cloud-env.mjs --host <hostname> --admin <main admin email> [--acme-email <real email>] [--smoke] [--keep-keys]");
  process.exit(1);
}

const local = join(dirname(fileURLToPath(import.meta.url)), "..", "local");
const target = join(local, "cloud-app.env");

// Reuse keys of an existing file with --keep-keys, so the main admin can be changed without invalidating data.
const kept = {};
if (args.includes("--keep-keys")) {
  for (const line of readFileSync(target, "utf8").split(/\r?\n/)) {
    const m = line.match(/^export (\w+)='(.*)'$/);
    if (m) kept[m[1]] = m[2];
  }
}

const pw = {};
for (const line of readFileSync(join(local, "gcp.env"), "utf8").split(/\r?\n/)) {
  const m = line.match(/^PW_(\w+)=(.*)$/);
  if (m) pw[m[1]] = m[2];
}

let priv = kept.JWT_PRIVATE_KEY_PEM;
let pub = kept.JWT_PUBLIC_KEY_PEM;
if (!priv) {
  const { publicKey, privateKey } = generateKeyPairSync("rsa", {
    modulusLength: 2048,
    publicKeyEncoding: { type: "spki", format: "pem" },
    privateKeyEncoding: { type: "pkcs8", format: "pem" },
  });
  const oneLine = (pem) => pem.trim().replace(/\r?\n/g, "\\n");
  priv = oneLine(privateKey);
  pub = oneLine(publicKey);
}
const keep = (k, make) => kept[k] ?? make();
const token = () => randomBytes(24).toString("hex");
const b64 = () => randomBytes(32).toString("base64");

const values = {
  DOMAIN: host,
  ACME_EMAIL: opt("acme-email") ?? admin,
  APP_BASE_URL: `https://${host}`,
  APP_MAIN_ADMIN_EMAIL: admin,
  JWT_PRIVATE_KEY_PEM: priv,
  JWT_PUBLIC_KEY_PEM: pub,
  PII_ENC_KEY: keep("PII_ENC_KEY", b64),
  PII_HMAC_KEY: keep("PII_HMAC_KEY", b64),
  IDENTITY_FEED_KEY: keep("IDENTITY_FEED_KEY", token),
  CATALOG_FEED_KEY: keep("CATALOG_FEED_KEY", token),
  ORDER_FEED_KEY: keep("ORDER_FEED_KEY", token),
  PAYMENT_FEED_KEY: keep("PAYMENT_FEED_KEY", token),
  FLEET_FEED_KEY: keep("FLEET_FEED_KEY", token),
  DB_PASSWORD_IDENTITY: pw.IDENTITY,
  DB_PASSWORD_CATALOG: pw.CATALOG,
  DB_PASSWORD_ORDER: pw.ORDER,
  DB_PASSWORD_PAYMENT: pw.PAYMENT,
  DB_PASSWORD_FLEET: pw.FLEET,
  // Sandbox only: the fake gateway pays every order and the logging providers write OTPs and links to the log.
  GATEWAY: "fake",
  ALLOW_FAKE_GATEWAY: "true",
  SMS_PROVIDER: "logging",
  EMAIL_PROVIDER: "logging",
  SEED_DEMO_DATA: "true",
  RUN_SMOKE: args.includes("--smoke") ? "1" : "0",
};
for (const [k, v] of Object.entries(values)) {
  if (v === undefined || v === "") {
    console.error(`missing value for ${k}`);
    process.exit(1);
  }
}
const lines = ["# Generated by deploy/scripts/gen-cloud-env.mjs. Never commit.", ...Object.entries(values).map(([k, v]) => `export ${k}='${v}'`), ""];
writeFileSync(target, lines.join("\n"), { encoding: "utf8" });
console.log(`Wrote ${target} (${Object.keys(values).length} values, main admin ${admin}, smoke ${values.RUN_SMOKE})`);
